package com.medibook.scheduler;

import com.medibook.dto.GenerateSlotsRequest;
import com.medibook.email.EmailService;
import com.medibook.entity.Appointment;
import com.medibook.entity.AppointmentStatus;
import com.medibook.entity.Doctor;
import com.medibook.repository.AppointmentRepository;
import com.medibook.repository.DoctorRepository;
import com.medibook.service.NotificationService;
import com.medibook.service.SlotService;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.scheduling.annotation.Scheduled;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

import java.time.Duration;
import java.time.Instant;
import java.time.LocalDate;
import java.time.format.DateTimeFormatter;
import java.util.List;

@Component
@RequiredArgsConstructor
@Slf4j
public class AppointmentScheduler {

    private final AppointmentRepository appointmentRepository;
    private final DoctorRepository doctorRepository;
    private final SlotService slotService;
    private final EmailService emailService;
    private final NotificationService notificationService;

    private static final DateTimeFormatter DATE_FMT = DateTimeFormatter.ofPattern("MMM dd, yyyy");
    private static final DateTimeFormatter TIME_FMT = DateTimeFormatter.ofPattern("hh:mm a");

    /**
     * Runs every 15 minutes to send reminders for appointments coming up in ~24 hours and ~1 hour.
     */
    @Scheduled(cron = "0 */15 * * * *")
    @Transactional
    public void sendUpcomingReminders() {
        LocalDate today = LocalDate.now();
        LocalDate tomorrow = today.plusDays(1);

        // Fetch active appointments for today and tomorrow
        List<Appointment> upcoming = appointmentRepository.findActiveAppointmentsOnDate(tomorrow);
        upcoming.addAll(appointmentRepository.findActiveAppointmentsOnDate(today));

        Instant now = Instant.now();

        for (Appointment apt : upcoming) {
            Instant slotStart = apt.getSlot().getSlotStart();
            Duration diff = Duration.between(now, slotStart);
            long minutesUntil = diff.toMinutes();

            // 24-hour reminder window: between 23h45m (1425m) and 24h15m (1455m)
            if (minutesUntil >= 1425 && minutesUntil <= 1455) {
                log.info("Sending 24h reminder for appointment {}", apt.getReferenceNo());
                emailService.sendAppointmentReminder(
                        apt.getPatient().getUser().getEmail(),
                        apt.getPatient().getFullName(),
                        apt.getDoctor().getFullName(),
                        apt.getAppointmentDate().format(DATE_FMT) + " at " + apt.getStartTime().format(TIME_FMT),
                        "24-Hour"
                );
                notificationService.createNotification(
                        apt.getPatient().getUser(),
                        "Appointment Reminder (Tomorrow)",
                        String.format("You have an upcoming appointment with Dr. %s tomorrow at %s.",
                                apt.getDoctor().getFullName(), apt.getStartTime().format(TIME_FMT)),
                        "REMINDER"
                );
            }

            // 1-hour reminder window: between 45m and 65m
            if (minutesUntil >= 45 && minutesUntil <= 65) {
                log.info("Sending 1h reminder for appointment {}", apt.getReferenceNo());
                emailService.sendAppointmentReminder(
                        apt.getPatient().getUser().getEmail(),
                        apt.getPatient().getFullName(),
                        apt.getDoctor().getFullName(),
                        apt.getAppointmentDate().format(DATE_FMT) + " at " + apt.getStartTime().format(TIME_FMT),
                        "1-Hour"
                );
                notificationService.createNotification(
                        apt.getPatient().getUser(),
                        "Appointment in 1 Hour",
                        String.format("Reminder: Your consultation with Dr. %s starts at %s.",
                                apt.getDoctor().getFullName(), apt.getStartTime().format(TIME_FMT)),
                        "REMINDER"
                );
            }
        }
    }

    /**
     * Runs daily at 2:00 AM to automatically maintain 14 days of booking slots for all active doctors.
     */
    @Scheduled(cron = "0 0 2 * * ?")
    public void autoGenerateDoctorSlots() {
        log.info("Starting nightly automated slot generation job...");
        List<Doctor> doctors = doctorRepository.findAll().stream()
                .filter(d -> d.isApproved() && d.isAvailable())
                .toList();

        LocalDate start = LocalDate.now().plusDays(1);
        LocalDate end = LocalDate.now().plusDays(14);
        GenerateSlotsRequest req = new GenerateSlotsRequest(start, end);

        for (Doctor doctor : doctors) {
            try {
                int generated = slotService.generateSlots(doctor.getId(), req);
                if (generated > 0) {
                    log.info("Auto-generated {} slots for Dr. {}", generated, doctor.getFullName());
                }
            } catch (Exception e) {
                log.warn("Could not auto-generate slots for doctor {}: {}", doctor.getId(), e.getMessage());
            }
        }
        log.info("Nightly slot generation completed.");
    }

    /**
     * Runs every 30 minutes to clean up past pending or unconfirmed appointments and mark them NO_SHOW if past.
     */
    @Scheduled(cron = "0 */30 * * * *")
    @Transactional
    public void markPastUnattendedAppointments() {
        LocalDate yesterday = LocalDate.now().minusDays(1);
        List<Appointment> pastActive = appointmentRepository.findActiveAppointmentsOnDate(yesterday);
        for (Appointment apt : pastActive) {
            if (apt.getStatus() == AppointmentStatus.PENDING || apt.getStatus() == AppointmentStatus.CONFIRMED) {
                apt.setStatus(AppointmentStatus.NO_SHOW);
                appointmentRepository.save(apt);
                log.info("Appointment {} auto-marked as NO_SHOW", apt.getReferenceNo());
            }
        }
    }
}
